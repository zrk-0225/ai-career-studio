  /* 取出某个方向在指定路线下的学习路径。
     有对应路线就用 pathBranch 覆盖掉同名的那一步，其余保持原样。
     刻意不写死下标：靠"时间前缀"匹配，这样以后往 path 中间插一步也不会错位。
     匹配不到就原样返回——多出来的一步会被丢掉，所以 selfCheck 里
     专门校验过每个 when 都能在 path 里找到。 */
  AICS.pathFor = function (dir, trackKey) {
    var steps = (dir.path || []).slice();
    var branch = (dir.pathBranch || {})[trackKey];
    if (!branch) return steps;
    branch.forEach(function (b) {
      for (var i = 0; i < steps.length; i++) {
        /* 每一步都写成「时间：做什么」，拿冒号前的时间段去匹配 */
        if (String(steps[i]).split('：')[0] === b.when) {
          steps[i] = b.when + '：' + b.what;
          return;
        }
      }
    });
    return steps;
  };

